CREATE TABLE zips (
    id UUID PRIMARY KEY,
    city TEXT NOT NULL,
    pop INTEGER NOT NULL,
    state TEXT NOT NULL,
    zip INTEGER NOT NULL
);

CREATE TABLE zips_loc (
    id BIGSERIAL PRIMARY KEY,
    zips_id UUID NOT NULL,
    x DOUBLE PRECISION NOT NULL,
    y DOUBLE PRECISION NOT NULL,
    FOREIGN KEY (zips_id) REFERENCES zips (id) DEFERRABLE INITIALLY DEFERRED
);